#!/usr/bin/env bash
# The team's roles (CABINET.md, "Seats"; concepts in docs/concepts.md).
#
#   bin/role.sh build [--check]
#       Build the definition of every role in CABINET_ROLES (cabinet.env) and every builder that owns
#       a repo in the team table of AGENTS.md: the kit's role (.cabinet/roles/<role>.md) with this
#       project's notes (roles/<role>.md, no frontmatter) appended under "Project notes", or the
#       project's own whole role (roles/<role>.md with frontmatter), which wins over a kit role of the
#       same name. Writes agents/<role>.md, which any agent tool reads, and .claude/agents/<role>.md.
#       Inside a project, also the project's .claude/agents/ and the "Agent team" pointer in the
#       instruction files agents read there (private: only files the project does not track, kept out
#       of its git). --check: exit 1 when a built file is out of date, changing nothing.
#   bin/role.sh draft <role>
#       Draft, or redraft, a role this project added (cabinet role add) with the configured agent
#       tool: chief-of-staff starts from the owner's brief in roles/<role>.md, learns the project and
#       writes the whole role as CABINET.md, "Drafting a role", says. It may cost money; asking an
#       agent in a session to draft the role does the same.
#   bin/role.sh list [--json]
#       Every role on the team (name, kind: kit, optional, builder or project; drafted or not) and the
#       optional kit roles that are off.
set -euo pipefail
source "$(dirname "$0")/lib.sh"

r_build() {
MARK="<!-- Generated by bin/role.sh build. Edit roles/<role>.md, never this file. -->"

build() {  # build <out-dir>
  local out=$1 role core own
  mkdir -p "$out"
  for role in $(team_roles); do
    core="$K/roles/$role.md" own="$WS/roles/$role.md"
    # The marker goes right after the frontmatter, which must stay first.
    if [[ -f "$own" ]] && head -1 "$own" | grep -qx -- '---'; then
      # A whole role of the project's own, used as it is, even when a kit role (perhaps one
      # added by a later kit) has the same name: the project's role is never mixed into it.
      awk -v m="${MARK//<role>/$role}" '{print} /^---$/ && ++n == 2 {print ""; print m}' "$own" > "$out/$role.md"
    elif [[ -f "$core" ]]; then
      awk -v m="${MARK//<role>/$role}" '{print} /^---$/ && ++n == 2 {print ""; print m}' "$core" > "$out/$role.md"
      if [[ -f "$own" ]]; then printf '\n## Project notes\n\n' >> "$out/$role.md"; cat "$own" >> "$out/$role.md"; fi
    elif [[ -f "$own" ]]; then
      echo "roles/$role.md needs frontmatter (name, description), as a kit role has" >&2; exit 1
    else
      echo "role '$role' is in CABINET_ROLES but neither the kit nor roles/ has it" >&2; exit 1
    fi
  done
}

# Where the definitions go. Inside a project, also the project's .claude/agents/,
# because Claude Code looks there when it starts in the project.
dirs=("$WS/agents" "$WS/.claude/agents")
[[ -n "$HOST" ]] && dirs+=("$HOST/.claude/agents")
# Generated by this script: its exact marker line for that role, nothing looser.
generated() { local role; role="$(basename "$1" .md)"; grep -qxF "${MARK//<role>/$role}" "$1" 2>/dev/null; }
show() { local p=$1; [[ -n "$HOST" && "$p" == "$HOST/"* && "$p" != "$WS/"* ]] && echo "../${p#"$HOST/"}" || echo "${p#"$WS/"}"; }

if [[ "${1:-}" == --check ]]; then  # report only
  tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
  build "$tmp"
  for d in "${dirs[@]}"; do
    for f in "$tmp"/*.md; do
      dst="$d/$(basename "$f")"
      # A hand-made file of the same name is the project's own: left alone, not checked.
      [[ -f "$dst" ]] && ! generated "$dst" && continue
      cmp -s "$f" "$dst" || { echo "$(show "$dst") is out of date"; exit 1; }
    done
    for f in "$d"/*.md; do
      generated "$f" && [[ ! -f "$tmp/$(basename "$f")" ]] && { echo "$(show "$f") is no longer a role"; exit 1; }
    done
  done
  exit 0
fi

tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT
build "$tmp"
ex=""
if [[ "$CABINET_LAYOUT" == inside && "$CABINET_VISIBILITY" == private ]]; then
  ex="$(git -C "$HOST" rev-parse --git-path info/exclude)"; [[ "$ex" == /* ]] || ex="$HOST/$ex"
  mkdir -p "$(dirname "$ex")"
  exclude() { grep -qxF "$1" "$ex" 2>/dev/null || echo "$1" >> "$ex"; }
  exclude /cabinet/
  # The pointer, only in files the project does not track: CLAUDE.local.md (Claude Code,
  # Grok), QWEN.local.md (Qwen), and AGENTS.md when the project has none of its own.
  pointer="The agent team for this project works from \`cabinet/\`. Before any task that involves handoffs, specs, verdicts or the team's roles, read \`cabinet/CABINET.md\`, then \`cabinet/AGENTS.md\`. Their paths are relative to \`cabinet/\`."
  for f in CLAUDE.local.md QWEN.local.md AGENTS.md; do
    git -C "$HOST" ls-files --error-unmatch "$f" >/dev/null 2>&1 && continue
    [[ "$f" == AGENTS.md && -e "$HOST/$f" ]] && ! grep -qF 'cabinet/CABINET.md' "$HOST/$f" && continue
    exclude "/$f"
    grep -qF 'cabinet/CABINET.md' "$HOST/$f" 2>/dev/null && continue
    [[ -s "$HOST/$f" ]] && printf '\n' >> "$HOST/$f"
    printf '%s\n' "## Agent team" "" "$pointer" >> "$HOST/$f"
  done
fi
for d in "${dirs[@]}"; do
  mkdir -p "$d"
  # Drop generated files for roles no longer listed; keep anything hand-made.
  for f in "$d"/*.md; do
    generated "$f" && [[ ! -f "$tmp/$(basename "$f")" ]] && rm "$f"
  done
  for f in "$tmp"/*.md; do
    dst="$d/$(basename "$f")"
    if [[ -f "$dst" ]] && ! generated "$dst"; then echo "  kept $(show "$dst"): it is not generated by cabinet"; continue; fi
    cp "$f" "$dst"
    # Private: the project's git never sees the role files placed in it.
    if [[ -n "$ex" && "$d" == "$HOST/.claude/agents" ]]; then
      line="/.claude/agents/$(basename "$f")"
      grep -qxF "$line" "$ex" 2>/dev/null || echo "$line" >> "$ex"
    fi
  done
done
echo "roles: $(team_roles)"
}

r_draft() {
role="${1:-}"
[[ "$role" =~ ^[a-z][a-z0-9-]*$ ]] || { echo "usage: bin/role.sh draft <role>" >&2; exit 2; }
rf="roles/$role.md"
[[ -f "$WS/$rf" ]] || { echo "no $rf: cabinet role add $role makes it" >&2; exit 2; }
head -1 "$WS/$rf" | grep -qx -- '---' || { echo "$rf is notes for a kit role, not a role of its own" >&2; exit 2; }

cd "$WS"
AGENT=chief-of-staff
PROMPT="Draft the role in $rf, as CABINET.md, \"Drafting a role\", says: keep its \"The owner's brief\" section word for word, learn the project, write the whole role in that file, list what you assumed under \"Assumed, for the owner to confirm\", fill its rows in the team tables of AGENTS.md and OPERATIONS.md, run bin/role.sh build, and commit those files alone (roles: draft $role). Change nothing else."
mkdir -p -m 700 "$LOGDIR"; log="$LOGDIR/role-$role.log"
echo "=== $(date '+%F %T') draft $role ($CABINET_RUNNER)" >> "$log"
echo "Drafting $role with $CABINET_RUNNER, as chief-of-staff. It takes a few minutes and prints nothing until it finishes."
SPEND_LABEL="role draft $role" run_agent </dev/null 2>&1 | tee -a "$log" || { echo "The draft did not finish: see $log" >&2; exit 1; }
grep -q '^description: TBD' "$rf" && { echo "$rf is still not drafted (its description is TBD): see $log" >&2; exit 1; }
r_build >/dev/null
echo
echo "Drafted $rf. Read it, and answer what it lists under \"Assumed, for the owner to confirm\" (the brief carries them too)."
}

r_list() {
  local json=0 a r kind state
  for a in "$@"; do case "$a" in --json) json=1 ;; *) echo "usage: bin/role.sh list [--json]" >&2; exit 2 ;; esac; done
  {
    for r in $(team_roles); do
      if [[ -f "$WS/roles/$r.md" ]] && head -1 "$WS/roles/$r.md" | grep -qx -- '---'; then
        kind=project; state=on; grep -q '^description: TBD' "$WS/roles/$r.md" && state="on, not drafted"
      elif has "$BUILDERS" "$r"; then kind=builder; state=on
      elif has "$ROLES_OPTIONAL" "$r"; then kind=optional; state=on
      else kind=kit; state=on; fi
      printf '%s\t%s\t%s\n' "$r" "$kind" "$state"
    done
    for r in $ROLES_OPTIONAL; do has "$(team_roles)" "$r" || printf '%s\toptional\toff\n' "$r"; done
  } > "$K/roles.list"
  if ((json)); then
    jq -Rn '[inputs | split("\t") | {name: .[0], kind: .[1], on: (.[2] | startswith("on")), drafted: (.[2] != "on, not drafted")}]' < "$K/roles.list"
  else
    awk -F'\t' '{printf "%-20s %-9s %s\n", $1, $2, $3}' "$K/roles.list"
  fi
  rm -f "$K/roles.list"
}

verb="${1:-}"; (($#)) && shift
case "$verb" in
  build) r_build "$@" ;;
  draft) r_draft "$@" ;;
  list) r_list "$@" ;;
  *) echo "usage: bin/role.sh build|draft|list (see the top of this file)" >&2; exit 2 ;;
esac
