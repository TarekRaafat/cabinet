// Writes llms-full.txt: every page llms.txt links to, in its order, in one file for agents.
// Run after changing any doc: node tools/build-llms-full.js [--check]. npm test runs --check.
"use strict";
const fs = require("node:fs");
const path = require("node:path");

const kit = path.dirname(__dirname);
const read = (p) => fs.readFileSync(path.join(kit, p), "utf8");
const llms = read("llms.txt");
const pages = [...llms.matchAll(/\]\(([^)#\s]+)\)/g)].map((m) => m[1]).filter((p) => !/^[a-z]+:\/\//.test(p) && p !== "llms-full.txt");
const out = [llms.split("\n## ")[0].trim(), "",
  "This file is every page listed in llms.txt, in that order, generated by tools/build-llms-full.js. " +
  "Links between pages are relative to the repository root.", ""];
for (const p of new Set(pages)) out.push("", "=".repeat(72), `File: ${p}`, "=".repeat(72), "", read(p).trim(), "");
const text = out.join("\n").trimEnd() + "\n";
const target = path.join(kit, "llms-full.txt");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== text) {
    console.log("FAIL: llms-full.txt is out of date: run npm run docs");
    process.exit(1);
  }
} else fs.writeFileSync(target, text);
