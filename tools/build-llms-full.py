"""Writes llms-full.txt: every page llms.txt links to, in its order, in one file for agents.
Run after changing any doc: python3 -I tools/build-llms-full.py [--check]. npm test runs --check."""
import os, re, sys

kit = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
read = lambda p: open(os.path.join(kit, p), encoding="utf-8").read()
llms = read("llms.txt")
pages = [p for p in re.findall(r"\]\(([^)#\s]+)\)", llms) if not re.match(r"[a-z]+://", p) and p != "llms-full.txt"]
out = [llms.split("\n## ")[0].strip(), "",
       "This file is every page listed in llms.txt, in that order, generated by tools/build-llms-full.py. "
       "Links between pages are relative to the repository root.", ""]
for p in dict.fromkeys(pages):
    out += ["", "=" * 72, f"File: {p}", "=" * 72, "", read(p).strip(), ""]
text = "\n".join(out).rstrip() + "\n"
target = os.path.join(kit, "llms-full.txt")
if "--check" in sys.argv:
    if not os.path.exists(target) or open(target, encoding="utf-8").read() != text:
        print("FAIL: llms-full.txt is out of date: run python3 -I tools/build-llms-full.py")
        sys.exit(1)
else:
    open(target, "w", encoding="utf-8").write(text)
